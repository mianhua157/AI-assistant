PROMPTS = {
    "definition": DEFINITION_PROMPT,
    "comparison": COMPARISON_PROMPT,
    "summary": SUMMARY_PROMPT,
    "quiz": QUIZ_PROMPT,
    "diagnosis": DIAGNOSIS_PROMPT,
    "study_plan": STUDY_PLAN_PROMPT,
    "general_qa": GENERAL_QA_PROMPT,
}


def select_prompt(intent: str) -> str:
    return PROMPTS.get(intent, GENERAL_QA_PROMPT)
